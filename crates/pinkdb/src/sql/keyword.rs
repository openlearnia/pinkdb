//! SQL keyword table shared by the PEG grammar.
//!
//! Keywords are matched case-insensitively against identifier-shaped words;
//! anything not in the table is a plain identifier. The grammar's `ident`
//! rule rejects reserved keywords (double-quote them to use the word as a
//! name).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Keyword {
    Select,
    Distinct,
    From,
    Where,
    Group,
    By,
    Having,
    Order,
    Asc,
    Desc,
    Limit,
    Join,
    Inner,
    Left,
    Right,
    Outer,
    Full,
    Cross,
    On,
    As,
    And,
    Or,
    Not,
    Null,
    Is,
    Between,
    Create,
    Table,
    Insert,
    Into,
    Values,
    True,
    False,
    With,
    In,
    Exists,
    Date,
    Timestamp,
    Over,
    Partition,
    Rows,
    Row,
    Range,
    Unbounded,
    Preceding,
    Following,
    Current,
    Update,
    Delete,
    Set,
    Begin,
    Commit,
    Rollback,
    Transaction,
    Union,
    Intersect,
    Except,
    Offset,
    View,
    Drop,
    Cast,
    Like,
    Case,
    When,
    Then,
    Else,
    End,
    Use,
    Database,
    Load,
    Extension,
    Index,
}

impl Keyword {
    pub(crate) fn lookup(s: &str) -> Option<Keyword> {
        Some(match s.to_ascii_uppercase().as_str() {
            "SELECT" => Keyword::Select,
            "DISTINCT" => Keyword::Distinct,
            "FROM" => Keyword::From,
            "WHERE" => Keyword::Where,
            "GROUP" => Keyword::Group,
            "BY" => Keyword::By,
            "HAVING" => Keyword::Having,
            "ORDER" => Keyword::Order,
            "ASC" => Keyword::Asc,
            "DESC" => Keyword::Desc,
            "LIMIT" => Keyword::Limit,
            "JOIN" => Keyword::Join,
            "INNER" => Keyword::Inner,
            "LEFT" => Keyword::Left,
            "RIGHT" => Keyword::Right,
            "OUTER" => Keyword::Outer,
            "FULL" => Keyword::Full,
            "CROSS" => Keyword::Cross,
            "ON" => Keyword::On,
            "AS" => Keyword::As,
            "AND" => Keyword::And,
            "OR" => Keyword::Or,
            "NOT" => Keyword::Not,
            "NULL" => Keyword::Null,
            "IS" => Keyword::Is,
            "BETWEEN" => Keyword::Between,
            "CREATE" => Keyword::Create,
            "TABLE" => Keyword::Table,
            "INSERT" => Keyword::Insert,
            "INTO" => Keyword::Into,
            "VALUES" => Keyword::Values,
            "TRUE" => Keyword::True,
            "FALSE" => Keyword::False,
            "WITH" => Keyword::With,
            "IN" => Keyword::In,
            "EXISTS" => Keyword::Exists,
            "DATE" => Keyword::Date,
            "TIMESTAMP" => Keyword::Timestamp,
            "OVER" => Keyword::Over,
            "PARTITION" => Keyword::Partition,
            "ROWS" => Keyword::Rows,
            "ROW" => Keyword::Row,
            "RANGE" => Keyword::Range,
            "UNBOUNDED" => Keyword::Unbounded,
            "PRECEDING" => Keyword::Preceding,
            "FOLLOWING" => Keyword::Following,
            "CURRENT" => Keyword::Current,
            "UPDATE" => Keyword::Update,
            "DELETE" => Keyword::Delete,
            "SET" => Keyword::Set,
            "BEGIN" => Keyword::Begin,
            "COMMIT" => Keyword::Commit,
            "ROLLBACK" => Keyword::Rollback,
            "TRANSACTION" => Keyword::Transaction,
            "UNION" => Keyword::Union,
            "INTERSECT" => Keyword::Intersect,
            "EXCEPT" => Keyword::Except,
            "OFFSET" => Keyword::Offset,
            "VIEW" => Keyword::View,
            "DROP" => Keyword::Drop,
            "CAST" => Keyword::Cast,
            "LIKE" => Keyword::Like,
            "CASE" => Keyword::Case,
            "WHEN" => Keyword::When,
            "THEN" => Keyword::Then,
            "ELSE" => Keyword::Else,
            "END" => Keyword::End,
            "USE" => Keyword::Use,
            "DATABASE" => Keyword::Database,
            "LOAD" => Keyword::Load,
            "EXTENSION" => Keyword::Extension,
            "INDEX" => Keyword::Index,
            _ => return None,
        })
    }
}
