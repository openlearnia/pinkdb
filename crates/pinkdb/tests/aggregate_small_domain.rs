//! Wave 123c: grouping by a small key domain (a dense code table instead of
//! hashing encoded keys) and summing DECIMAL cells per group per chunk. Each
//! query's result is pinned to DuckDB 2.0 on the same generated data: keys
//! with NULLs first and in the middle, 2- and 3-column keys, a column whose
//! later chunks pass the small-domain limit (the hashed fallback), and
//! DECIMAL SUM/AVG through the bulk path.

use pinkdb::{PinkDb, QueryResult, Value};

/// The generator `gen.py` used for DuckDB's side: a 64-bit LCG.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        self.0 >> 33
    }
}

fn decimal(cents: i64) -> String {
    let sign = if cents < 0 { "-" } else { "" };
    let c = cents.unsigned_abs();
    format!("{sign}{}.{:02}", c / 100, c % 100)
}

fn store() -> PinkDb {
    let mut r = Lcg(7);
    let mut rows = Vec::with_capacity(9000);
    for i in 0..9000i64 {
        let a = if i % 97 == 0 {
            "NULL".to_string()
        } else {
            format!("'{}'", ["A", "N", "R"][(r.next() % 3) as usize])
        };
        let b = if i % 89 == 5 {
            "NULL".to_string()
        } else {
            format!("'{}'", ["F", "O"][(r.next() % 2) as usize])
        };
        let c = if i % 13 == 3 {
            "NULL".to_string()
        } else {
            (i % 5).to_string()
        };
        let w = (i / 3000) * 1000 + if i >= 6000 { i % 40 } else { i % 7 };
        let v = (r.next() % 19_999_999) as i64;
        let x = if i % 31 == 0 {
            "NULL".to_string()
        } else {
            decimal(v - 9_999_999)
        };
        rows.push(format!("({a},{b},{c},{w},{x})"));
    }
    let mut db = PinkDb::new();
    db.execute("CREATE TABLE t (a VARCHAR, b VARCHAR, c INTEGER, w INTEGER, x DECIMAL(15,2));")
        .unwrap();
    db.execute(&format!("INSERT INTO t VALUES {};", rows.join(",")))
        .unwrap();
    db
}

