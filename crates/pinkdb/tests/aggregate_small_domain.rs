#[test]
fn small_domain_groups_and_bulk_decimal_sums_match_duckdb() {
    let mut db = store();
    for (sql, expected) in CASES {
        let rows = match db.execute(sql).unwrap().pop().unwrap() {
            QueryResult::Selected { rows, .. } => rows,
            other => panic!("expected rows from {sql}, got {other:?}"),
        };
        let got: Vec<String> = rows
            .iter()
            .map(|r| {
                r.iter()
                    .map(|v| match v {
                        Value::Null => "NULL".to_string(),
                        v => v.to_string(),
                    })
                    .collect::<Vec<_>>()
                    .join(",")
            })
            .collect();
        assert_eq!(got.join("\n"), expected, "{sql}");
    }
}
