#!/usr/bin/env python3
"""Regenerate the wave tables of src/pages/roadmap.html from ROADMAP.md.

ROADMAP.md is the single source of truth; this keeps the docs page from
drifting (it once stopped at wave 26 while the tracker reached 40).

    python3 website/tools/sync_roadmap.py           # rewrite the page
    python3 website/tools/sync_roadmap.py --check   # exit 1 if it is stale

Stdlib only.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ROADMAP = ROOT / "ROADMAP.md"
PAGE = ROOT / "website" / "src" / "pages" / "roadmap.html"
START = "<!-- roadmap:begin (generated by website/tools/sync_roadmap.py) -->"
END = "<!-- roadmap:end -->"
MAX_SCOPE = 220


def waves() -> list[tuple[str, str, str]]:
    rows = []
    for line in ROADMAP.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| (\d+[a-z]?) \| (.*?) \| (done|queued|in progress) \|", line)
        if m:
            rows.append((m.group(1), m.group(2), m.group(3)))
    if not rows:
        sys.exit("sync_roadmap: no wave rows found in ROADMAP.md")
    return rows


def scope_html(scope: str) -> str:
    if len(scope) > MAX_SCOPE:
        cut = scope[:MAX_SCOPE].rsplit(" ", 1)[0].rstrip(",;:")
        # Never leave an unbalanced code span.
        if cut.count("`") % 2:
            cut = cut[: cut.rfind("`")].rstrip()
        scope = cut + " …"
    parts = scope.split("`")
    return "".join(
        f"<code>{html.escape(p)}</code>" if i % 2 else html.escape(p)
        for i, p in enumerate(parts)
    )


def badge(status: str) -> str:
    cls = {"done": "done", "queued": "queued", "in progress": "now"}[status]
    return f'<span class="badge {cls}">{status}</span>'


def table(rows) -> str:
    body = "\n".join(
        f"    <tr><td>{w}</td><td>{scope_html(s)}</td><td>{badge(st)}</td></tr>"
        for w, s, st in rows
    )
    return (
        '<div class="table-wrap">\n<table>\n'
        "  <thead><tr><th>Wave</th><th>Scope</th><th>Status</th></tr></thead>\n"
        f"  <tbody>\n{body}\n  </tbody>\n</table>\n</div>"
    )


def generated() -> str:
    rows = waves()
    done = [r for r in rows if r[2] == "done"]
    rest = [r for r in rows if r[2] != "done"]
    return (
        f"{START}\n"
        f"<p class=\"doc-meta\">Generated from ROADMAP.md: {len(done)} waves done, "
        f"latest <strong>{done[-1][0] if done else '—'}</strong>; {len(rest)} queued or in "
        "progress. Per-wave evidence (test counts, benchmarks, sizes) lives in ROADMAP.md.</p>\n\n"
        "<h2>Shipped</h2>\n\n"
        f"{table(done)}\n\n"
        "<h2>Queued</h2>\n\n"
        f"{table(rest)}\n"
        f"{END}"
    )


def main() -> int:
    page = PAGE.read_text(encoding="utf-8")
    if START in page and END in page:
        head, rest = page.split(START, 1)
        _, tail = rest.split(END, 1)
    else:
        # First run: replace the hand-written tables (Shipped … up to Deferred).
        i = page.index("<h2>Shipped")
        j = page.index("<h2>Deferred</h2>")
        head, tail = page[:i], "\n\n" + page[j:]
    new = head + generated() + tail
    if "--check" in sys.argv[1:]:
        if new != page:
            print("website/src/pages/roadmap.html is stale; run website/tools/sync_roadmap.py")
            return 1
        return 0
    PAGE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
