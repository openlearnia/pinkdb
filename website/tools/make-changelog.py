#!/usr/bin/env python3
"""Render CHANGELOG.md (repo root) into the docs site's changelog fragment.

Run from anywhere:  python3 website/tools/make-changelog.py

The site is plain fragments in `website/src/pages/`; this tool keeps
`changelog.html` in lockstep with the single changelog source of truth.
CI re-runs it and diffs, so a stale fragment fails the build.
"""

from __future__ import annotations

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "CHANGELOG.md"
OUT = ROOT / "website" / "src" / "pages" / "changelog.html"

REPO = "https://github.com/openlearnia/pinkdb/blob/main"

HEADER = "\n".join(
    [
        "<!-- generated by website/tools/make-changelog.py from CHANGELOG.md —",
        "     edit CHANGELOG.md, regenerate, and commit both. -->",
        "<h1>Changelog</h1>",
        "",
        '<p class="doc-meta">One entry per wave, newest first — what changed on',
        "pinkdb's user-facing surfaces. The full engineering detail (probes, gate",
        "counts, integration notes) lives in the",
        f'<a href="{REPO}/ROADMAP.md#progress-log" rel="noopener">ROADMAP',
        "progress log</a>.</p>",
        "",
    ]
)

FOOTER = "\n".join(
    [
        '<ul class="next-links">',
        '  <li><a href="{{root}}docs/roadmap.html">Roadmap →</a></li>',
        f'  <li><a href="{REPO}/CHANGELOG.md" rel="noopener">CHANGELOG.md on GitHub →</a></li>',
        "</ul>",
        "",
    ]
)

CODE = re.compile(r"`([^`]+)`")
BOLD = re.compile(r"\*\*([^*]+)\*\*")
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")


def inline(text: str) -> str:
    text = html.escape(text, quote=False)

    def link(m: re.Match[str]) -> str:
        label, url = m.group(1), m.group(2)
        if url.startswith("ROADMAP.md"):
            url = f"{REPO}/{url}"
        if not re.match(r"^(https?://|/|\.\.?/|#|\{\{)", url):
            return m.group(0)
        return f'<a href="{url}" rel="noopener">{label}</a>'

    text = LINK.sub(link, text)
    text = CODE.sub(r"<code>\1</code>", text)
    text = BOLD.sub(r"<strong>\1</strong>", text)
    return text


def render(md: str) -> str:
    # Everything after the first `## ` heading is the changelog body.
    body = md[md.index("\n## ") :]
    out: list[str] = [HEADER]
    para: list[str] = []
    item: list[str] = []
    in_list = False

    def close_para() -> None:
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para.clear()

    def close_list() -> None:
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    def close_item() -> None:
        if item:
            out.append("<li>" + inline(" ".join(item)) + "</li>")
            item.clear()

    for raw in body.splitlines():
        line = raw.rstrip()
        if line.startswith("### "):
            close_list()
            close_item()
            close_para()
            out.append("<h3>" + inline(line[4:]) + "</h3>")
        elif line.startswith("## "):
            close_list()
            close_item()
            close_para()
            out.append("<h2>" + inline(line[3:]) + "</h2>")
        elif line.startswith("- "):
            close_para()
            close_item()
            if not in_list:
                out.append("<ul>")
                in_list = True
            item.append(line[2:].strip())
        elif line.startswith("  ") and item:
            item.append(line.strip())  # wrapped list-item continuation
        elif not line.strip():
            close_item()
            close_list()
            close_para()
        else:
            close_list()
            close_item()
            para.append(line.strip())
    close_item()
    close_list()
    close_para()
    out.append(FOOTER)
    return "\n".join(out)


def main() -> int:
    generated = render(SRC.read_text())
    OUT.write_text(generated)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
